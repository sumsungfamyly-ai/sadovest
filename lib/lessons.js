function parse(raw) {
  return raw.split(/^@ /m).slice(1).map(b => {
    const L = b.split('\n'), [id, level, kind] = L[0].trim().split(' ');
    const o = { id: +id, level, free: kind === 'free', sections: [], quiz: [] }; let cur = null;
    for (const ln of L.slice(1)) {
      if (ln.startsWith('# ')) o.title = ln.slice(2).trim();
      else if (ln.startsWith('> ')) o.intro = ln.slice(2).trim();
      else if (ln.startsWith('## ')) { cur = [ln.slice(3).trim(), '']; o.sections.push(cur); }
      else if (ln.startsWith('!')) o.fact = ln.slice(1).trim();
      else if (ln.startsWith('$')) o.tip = ln.slice(1).trim();
      else if (ln.startsWith('~')) o.words = ln.slice(1).split(';').map(x => x.trim()).filter(Boolean);
      else if (ln.startsWith('?')) { const [q, ...r] = ln.slice(1).split('|'); o.quiz.push([q.trim(), ...r.map(x => x.trim())]); }
      else if (cur && ln.trim()) cur[1] += (cur[1] ? ' ' : '') + ln.trim();
    }
    return o;
  });
}
